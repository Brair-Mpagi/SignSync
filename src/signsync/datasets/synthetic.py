"""Build a synthetic corpus on disk.

Produces a complete, structurally valid corpus — manifest, landmark files, signer
profiles and consent records — from no real person. That gives the rest of the
project something to develop against before collection begins, gives CI a corpus to
run the training pipeline over, and gives ``data/samples/`` a fixture that is safe
to commit (``docs/data-protection.md``).

The consent records are synthetic too, and deliberately not uniform: one signer's
consent is withdrawn and one has lapsed retention, so that any code path which
quietly ignores consent fails against the sample corpus rather than in production.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date, timedelta
from pathlib import Path

from ..vision.synthetic import SignerStyle, stable_seed, synthetic_sentence, synthetic_sign
from .consent import ConsentRecord, ConsentRegistry, ConsentScope
from .schema import (
    AgeBand,
    ClipRecord,
    Corpus,
    Handedness,
    MarkerType,
    NonManualMarker,
    RecordingConditions,
    SignerProfile,
    SigningBackground,
)

__all__ = ["SyntheticCorpusSpec", "build_synthetic_corpus", "DEMO_VOCABULARY", "DEMO_SENTENCES"]

#: Placeholder vocabulary in the domains plan §9.2 prioritises (greetings, health,
#: everyday needs). These are English gloss labels for pipeline testing; they are
#: NOT a validated USL vocabulary (docs/limitations.md).
DEMO_VOCABULARY: tuple[str, ...] = (
    "HELLO",
    "THANK-YOU",
    "PLEASE",
    "YES",
    "NO",
    "HELP",
    "PAIN",
    "HOSPITAL",
    "DOCTOR",
    "MEDICINE",
    "WATER",
    "FOOD",
    "NAME",
    "WHERE",
    "WHAT",
    "ME",
    "YOU",
    "NEED",
    "SICK",
    "SCHOOL",
)

#: Continuous items, as (gloss sequence, English) pairs.
DEMO_SENTENCES: tuple[tuple[tuple[str, ...], str], ...] = (
    (("HOSPITAL", "WHERE"), "Where is the hospital?"),
    (("ME", "NEED", "HELP"), "I need help."),
    (("ME", "SICK", "PAIN"), "I am sick and in pain."),
    (("YOU", "NAME", "WHAT"), "What is your name?"),
    (("ME", "NEED", "WATER"), "I need water."),
    (("DOCTOR", "WHERE"), "Where is the doctor?"),
)

_DISTRICTS = ("Kampala", "Gulu", "Mbarara", "Jinja", "Arua", "Mbale")
_CONDITIONS = (
    RecordingConditions("daylight", "plain", "medium", "webcam", "clinic", "640x480"),
    RecordingConditions("indoor_fluorescent", "cluttered", "close", "phone", "school", "1280x720"),
    RecordingConditions("low_light", "plain", "far", "phone", "home", "640x480"),
    RecordingConditions(
        "daylight", "outdoor", "medium", "camcorder", "community_hall", "1920x1080"
    ),
)


@dataclass(frozen=True)
class SyntheticCorpusSpec:
    """What to generate."""

    n_signers: int = 6
    vocabulary: tuple[str, ...] = DEMO_VOCABULARY
    repeats_per_gloss: int = 2
    sentences: tuple[tuple[tuple[str, ...], str], ...] = DEMO_SENTENCES
    sentence_repeats: int = 1
    fps: float = 30.0
    name: str = "synthetic-demo"


def build_synthetic_corpus(
    root: str | Path,
    spec: SyntheticCorpusSpec | None = None,
    *,
    today: date | None = None,
) -> tuple[Corpus, ConsentRegistry]:
    """Write a synthetic corpus under ``root`` and return it with its consent registry."""
    spec = spec or SyntheticCorpusSpec()
    root = Path(root)
    (root / "landmarks").mkdir(parents=True, exist_ok=True)
    today = today or date.today()

    corpus = Corpus(
        name=spec.name,
        root=root,
        notes=(
            "Synthetic corpus generated by signsync.datasets.synthetic. Derived from no real "
            "person; contains no USL. For pipeline development and CI only."
        ),
    )
    registry = ConsentRegistry()

    signer_ids = [f"signer-{i:02d}" for i in range(spec.n_signers)]
    styles = _styles(signer_ids)
    for index, signer_id in enumerate(signer_ids):
        corpus.add_signer(_profile(signer_id, index, styles[signer_id]))
        registry.add(_consent(signer_id, index, today))

    for index, signer_id in enumerate(signer_ids):
        style = styles[signer_id]
        conditions = _CONDITIONS[index % len(_CONDITIONS)]

        for gloss in spec.vocabulary:
            for take in range(spec.repeats_per_gloss):
                clip_id = f"{signer_id}_{gloss}_{take}"
                sequence = synthetic_sign(
                    gloss, style, fps=spec.fps, seed=stable_seed(clip_id)
                )
                path = Path("landmarks") / f"{clip_id}.npz"
                sequence.save(root / path)
                corpus.add_clip(
                    ClipRecord(
                        clip_id=clip_id,
                        signer_id=signer_id,
                        glosses=(gloss,),
                        english=_english_for(gloss),
                        landmark_path=str(path),
                        duration=sequence.duration,
                        fps=spec.fps,
                        domain=_domain_for(gloss),
                        conditions=conditions,
                        annotator_id="synthetic",
                        markers=_markers_for((gloss,), sequence.duration),
                    )
                )

        for sentence_index, (glosses, english) in enumerate(spec.sentences):
            for take in range(spec.sentence_repeats):
                clip_id = f"{signer_id}_sent{sentence_index}_{take}"
                sequence = synthetic_sentence(list(glosses), style, fps=spec.fps)
                path = Path("landmarks") / f"{clip_id}.npz"
                sequence.save(root / path)
                spans = tuple(
                    (start / spec.fps, end / spec.fps)
                    for start, end, _ in sequence.meta["boundaries"]
                )
                corpus.add_clip(
                    ClipRecord(
                        clip_id=clip_id,
                        signer_id=signer_id,
                        glosses=tuple(glosses),
                        english=english,
                        landmark_path=str(path),
                        duration=sequence.duration,
                        fps=spec.fps,
                        domain="health",
                        boundaries=spans,
                        conditions=conditions,
                        annotator_id="synthetic",
                        markers=_markers_for(glosses, sequence.duration),
                    )
                )

    corpus.save()
    registry.save(root / "consent.json")
    return corpus, registry


def _styles(signer_ids: list[str]) -> dict[str, SignerStyle]:
    """One style per signer, with at least one left-handed signer guaranteed.

    Left-handed signers mirror every sign, so a corpus without one produces a model
    that fails completely on roughly a tenth of the population. Leaving that to the
    12% chance in :meth:`SignerStyle.derived` means small fixtures usually lack one,
    which is exactly the recruitment gap plan §9.3 exists to prevent.
    """
    styles = {sid: SignerStyle.derived(sid) for sid in signer_ids}
    if signer_ids and not any(s.left_handed for s in styles.values()):
        from dataclasses import replace

        target = signer_ids[min(1, len(signer_ids) - 1)]
        styles[target] = replace(styles[target], left_handed=True)
    return styles


def _profile(signer_id: str, index: int, style: SignerStyle) -> SignerProfile:
    return SignerProfile(
        signer_id=signer_id,
        age_band=list(AgeBand)[index % len(AgeBand)],
        background=list(SigningBackground)[index % len(SigningBackground)],
        district=_DISTRICTS[index % len(_DISTRICTS)],
        handedness=Handedness.LEFT if style.left_handed else Handedness.RIGHT,
        gender="unspecified",
        notes="synthetic",
    )


def _consent(signer_id: str, index: int, today: date) -> ConsentRecord:
    """Consent for a synthetic signer, varied so the gating code is exercised."""
    profile_age = list(AgeBand)[index % len(AgeBand)]
    is_minor = profile_age is AgeBand.UNDER_18

    scopes = {ConsentScope.TRAINING, ConsentScope.EVALUATION}
    if index % 2 == 0:
        scopes.add(ConsentScope.PUBLICATION)
    if index % 3 == 0:
        scopes.add(ConsentScope.OPEN_RELEASE)

    # One withdrawal and one lapsed retention, so any code path that ignores
    # consent fails here rather than in production.
    withdrawn = today - timedelta(days=5) if signer_id == "signer-04" else None
    retention = (
        today - timedelta(days=1)
        if signer_id == "signer-05"
        else today + timedelta(days=365 * 3)
    )

    return ConsentRecord(
        participant_id=signer_id,
        granted_on=today - timedelta(days=120),
        retention_until=retention,
        scopes=frozenset(scopes),
        delivered_by="synthetic-fixture",
        language="USL",
        withdrawn_on=withdrawn,
        is_minor=is_minor,
        guardian_name="synthetic guardian" if is_minor else None,
        guardian_relationship="parent" if is_minor else None,
        notes="Synthetic record. No real person consented to anything here.",
    )


def _domain_for(gloss: str) -> str:
    health = {"PAIN", "HOSPITAL", "DOCTOR", "MEDICINE", "SICK", "HELP"}
    education = {"SCHOOL", "NAME"}
    if gloss in health:
        return "health"
    if gloss in education:
        return "education"
    return "everyday"


def _english_for(gloss: str) -> str:
    return {
        "THANK-YOU": "thank you",
        "ME": "I",
    }.get(gloss, gloss.lower().replace("-", " "))


def _markers_for(glosses: tuple[str, ...], duration: float) -> tuple[NonManualMarker, ...]:
    """Attach the non-manual marker the gloss sequence implies.

    Question and negation marking is not optional decoration: brow position and head
    shake are how those distinctions are made (plan §8.7), so the synthetic corpus
    carries them and downstream code has something real to align against.
    """
    markers: list[NonManualMarker] = []
    if any(g in {"WHERE", "WHAT", "WHO", "WHY"} for g in glosses):
        markers.append(
            NonManualMarker(MarkerType.BROW_FURROW, 0.0, duration, 0.8, tuple(glosses))
        )
    elif "YES" in glosses:
        markers.append(NonManualMarker(MarkerType.HEAD_NOD, 0.0, duration, 0.7, tuple(glosses)))
    elif "NO" in glosses:
        markers.append(NonManualMarker(MarkerType.HEAD_SHAKE, 0.0, duration, 0.9, tuple(glosses)))
    return tuple(markers)
